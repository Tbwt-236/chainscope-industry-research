await assert.rejects(()=>validateImport({...template,url:'http://127.0.0.1'},data));
for(const [route,ids] of [['all_solid',['sldp']],['solid_separator',['qs']]]){
 const r=await research(data,'固态电池','2025-03-01',route);
 const path=scenario(data,r,'delay').paths.find(p=>p.node_id==='process');
 assert.deepEqual(path.company_ids,ids);
 assert.equal(path.evidence_ids.length,1);
}
