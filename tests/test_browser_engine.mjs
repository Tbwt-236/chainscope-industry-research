import baseAssert from 'node:assert/strict';
let checks=0;
const assert=new Proxy(baseAssert,{get(target,key){const value=target[key];return typeof value==='function'? (...args)=>{checks++;return value(...args);}:value;}});
import fs from 'node:fs';
import {research,grade,sensitivity,validateImport,scenario,compareReports} from '../dist/engine.mjs';
const data=JSON.parse(fs.readFileSync(new URL('../data/research.json',import.meta.url)));
const report=await research(data);
assert.equal(report.companies.length,6);
assert.deepEqual(report.evidence_graph.map(r=>r.evidence_level),['A','B','B','B','B','B','C']);
assert.equal(report.comparisons.length,2);
assert.equal(report.evidence_graph[0].financial.revenue_share,null);
assert.equal((await research(data,'固态电池','2023-01-01')).comparisons.length,0);
assert.ok((await research(data,'固态电池','2023-01-01')).evidence_graph.every(r=>r.evidence_level==='M'));
await assert.rejects(()=>research(data,'算力网络'));
await assert.rejects(()=>research(data,'固态电池目标价'));
await assert.rejects(()=>research(data,'固态电池','2025-02-30'));
assert.equal(sensitivity(-.2,.3,.7),1.8);
assert.equal(sensitivity(-.2,.3,1),0);
assert.throws(()=>sensitivity(-.2,2,.7));
assert.equal(scenario(data,report,'lithium_down').paths.length,3);
assert.throws(()=>scenario(data,report,'unknown'));
const evidence=structuredClone(data.evidence);evidence[0].summary+='虚构';
assert.equal((await grade(data.relations[0],evidence,'2025-03-01')).evidence_level,'M');
